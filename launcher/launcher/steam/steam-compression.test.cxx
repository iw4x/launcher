  void
  test_container_validation ()
  {
    check_throws ([]
    {
      compression::vzip_decompress (byte_view (fixture_vzip, 8));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_vzip, fixture_vzip + sizeof (fixture_vzip));
      d[d.size () - 1] = 'X';

      compression::vzip_decompress (byte_view (d.data (), d.size ()));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_vzip, fixture_vzip + sizeof (fixture_vzip));
      d[d.size () - 10] ^= 0xff;

      compression::vzip_decompress (byte_view (d.data (), d.size ()));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_vzip, fixture_vzip + sizeof (fixture_vzip));
      d[d.size () - 6] = 0xff;

      compression::vzip_decompress (byte_view (d.data (), d.size ()));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_vzstd,
                         fixture_vzstd + sizeof (fixture_vzstd));
      d[d.size () - 2] = 'X';

      compression::vzstd_decompress (byte_view (d.data (), d.size ()));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_vzstd,
                         fixture_vzstd + sizeof (fixture_vzstd));
      d[d.size () / 2] ^= 0xff;

      compression::vzstd_decompress (byte_view (d.data (), d.size ()));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_zip, fixture_zip + sizeof (fixture_zip));
      d[40] ^= 0xff;

      compression::zip_decompress (byte_view (d.data (), d.size ()));
    });
  }

  void
  test_depot_chunk_dispatch ()
  {
    assert (matches_plain (compression::decompress_depot_chunk (
      byte_view (fixture_vzip, sizeof (fixture_vzip)),
      sizeof (fixture_plain))));

    assert (matches_plain (compression::decompress_depot_chunk (
      byte_view (fixture_vzstd, sizeof (fixture_vzstd)),
      sizeof (fixture_plain))));

    assert (matches_plain (compression::decompress_depot_chunk (
      byte_view (fixture_zip, sizeof (fixture_zip)),
      sizeof (fixture_plain))));

    check_throws ([]
    {
      compression::decompress_depot_chunk (plain (), sizeof (fixture_plain));
    });

    check_throws ([]
    {
      compression::decompress_depot_chunk (plain ().subspan (0, 3), 3);
    });

    check_throws ([]
    {
      compression::decompress_depot_chunk (
        byte_view (fixture_vzip, sizeof (fixture_vzip)),
        sizeof (fixture_plain) - 1);
    });
  }

  void
  test_adler32_seed ()
  {
    assert (compression::adler32_steam (plain ()) == 0xf6724bb0u);

    assert (compression::adler32_steam (plain ()) != 0xf7424bb1u);

    assert (compression::adler32_steam (byte_view {}) == 0u);
  }
