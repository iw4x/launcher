  byte_view
  plain ()
  {
    return byte_view (fixture_plain, sizeof (fixture_plain));
  }

  bool
  matches_plain (const byte_buffer& b)
  {
    return b.size () == sizeof (fixture_plain) &&
           equal (b.begin (), b.end (), fixture_plain);
  }

  template <typename F>
  void
  check_throws (F f)
  {
    bool threw (false);

    try
    {
      f ();
    }
    catch (const compression::compression_error&)
    {
      threw = true;
    }

    assert (threw);
  }

  void
  test_gzip ()
  {
    byte_buffer r (compression::gzip_decompress (
      byte_view (fixture_gzip, sizeof (fixture_gzip)),
      sizeof (fixture_plain)));

    assert (matches_plain (r));
  }

  void
  test_gzip_rejects_bad_input ()
  {
    check_throws ([]
    {
      compression::gzip_decompress (
        byte_view (fixture_gzip, sizeof (fixture_gzip)),
        sizeof (fixture_plain) + 1);
    });

    check_throws ([]
    {
      compression::gzip_decompress (
        byte_view (fixture_gzip, sizeof (fixture_gzip) / 2),
        sizeof (fixture_plain));
    });

    check_throws ([]
    {
      compression::gzip_decompress (plain (), sizeof (fixture_plain));
    });

    check_throws ([]
    {
      vector<uint8_t> d (fixture_gzip, fixture_gzip + sizeof (fixture_gzip));
      d[d.size () / 2] ^= 0xff;

      compression::gzip_decompress (byte_view (d.data (), d.size ()),
                                    sizeof (fixture_plain));
    });
  }

